def _rebrand(text):

    text = re.sub(
        r"SamuelBet\s*(<span[^>]*>)\s*AI\s*(</span>)",
        r"Sporty\1Tips\2",
        text,
    )

    text = text.replace(
        "SamuelBet AI",
        "SportyTips",
    )

    text = text.replace(
        "SamuelBet",
        "SportyTips",
    )

    return text


