@app.post("/api/chat")
def chat():

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    text = str(
        data.get(
            "message",
            "",
        )
    ).strip()

    session = str(
        data.get(
            "session",
            "",
        )
    ).strip()

    text = text[:500]

    session = session[:64]

    if not text:
        return jsonify(
            error="Empty message."
        ), 400

    if not session:
        return jsonify(
            error="Missing session."
        ), 400

    if too_fast(
        client_ip()
    ):
        return jsonify(
            error=(
                "Slow down. "
                "Try again in a minute."
            )
        ), 429

    q, busy = start_turn(
        session,
        text,
    )

    if busy:
        return busy

    return stream_response(q)


# ============================================================
# /api/build
#
# Some versions of the frontend use /api/build
# instead of /api/chat.
#
# This accepts:
#   message
#   text
#   prompt
#   spec
#
# So the frontend does not break.
# ============================================================

@app.post("/api/build")
def api_build():

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    text = ""

    for key in (
        "message",
        "text",
        "prompt",
    ):

        value = data.get(key)

        if value:
            text = str(value).strip()
            break

    # If frontend sends an object called "spec",
    # convert it into a simple natural-language request.
    if not text and isinstance(
        data.get("spec"),
        dict,
    ):

        spec = data["spec"]

        parts = []

        target = (
            spec.get("target_odds")
            or spec.get("odds")
            or spec.get("target")
        )

        picks = (
            spec.get("picks")
            or spec.get("count")
            or spec.get("legs")
        )

        window = (
            spec.get("window")
            or "today"
        )

        risk = (
            spec.get("risk")
            or "normal"
        )

        straight = spec.get(
            "straight_win",
            False,
        )

        if straight:
            parts.append(
                "straight win"
            )

        if target:
            parts.append(
                f"{target} odds"
            )

        elif picks:
            parts.append(
                f"best {picks} picks"
            )

        else:
            parts.append(
                "best 5 picks"
            )

        parts.append(
            str(window)
        )

        if risk:
            parts.append(
                str(risk)
            )

        text = " ".join(parts)

    if not text:
        return jsonify(
            error="Empty build request."
        ), 400

    session = str(
        data.get(
            "session",
            "",
        )
    ).strip()[:64]

    if not session:
        return jsonify(
            error="Missing session."
        ), 400

    if too_fast(
        client_ip()
    ):
        return jsonify(
            error=(
                "Slow down. "
                "Try again in a minute."
            )
        ), 429

    q, busy = start_turn(
        session,
        text[:500],
    )

    if busy:
        return busy

    return stream_response(q)


