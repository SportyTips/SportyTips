    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    code = str(
        data.get(
            "code",
            "",
        )
    ).strip().upper()

    if not code:
        return jsonify(
            error="Enter a SportyBet code."
        ), 400

    if not CODE_OK.match(code):
        return jsonify(
            error="Invalid SportyBet code format."
        ), 400

    return jsonify(
        {
            "ok": True,
            "code": code,
            "message": (
                "Code format looks valid. "
                "Open it through SportyBet "
                "to verify the ticket."
            ),
        }
    )


