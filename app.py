@app.post("/api/build")
def api_build():

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    session = str(
        data.get(
            "session",
            "",
        )
    ).strip()[:64]

    if not session:

        return jsonify(
            error="Missing session."
        ), 400

    # --------------------------------------------------------
    # DIRECT TEXT
    # --------------------------------------------------------

    text = ""

    direct_keys = (
        "message",
        "text",
        "prompt",
        "request",
        "query",
        "build",
    )

    for key in direct_keys:

        value = data.get(key)

        if isinstance(value, str):

            value = value.strip()

            if value:

                text = value
                break

    # --------------------------------------------------------
    # SPEC SUPPORT
    # --------------------------------------------------------

    spec = data.get("spec")

    if isinstance(spec, str):

        try:

            parsed = json.loads(spec)

            if isinstance(parsed, dict):
                spec = parsed

        except Exception:

            if not text:
                text = spec.strip()

    if not isinstance(spec, dict):
        spec = {}

    # --------------------------------------------------------
    # MERGE TOP LEVEL + SPEC
    # --------------------------------------------------------

    def get_value(*keys):

        value = first_value(
            data,
            keys,
        )

        if value is not None:
            return value

        return first_value(
            spec,
            keys,
        )

    # --------------------------------------------------------
    # MODE
    # --------------------------------------------------------

    mode = get_value(
        "mode",
        "ticket_type",
        "ticketType",
    )

    mode_text = str(
        mode or ""
    ).strip().lower()

    mode_map = {
        "up2": "2UP win",
        "up1": "1UP win",
        "win": "plain win",
        "dc": "double chance",
        "straight": "straight win",
        "straight_win": "straight win",
    }

    # --------------------------------------------------------
    # SIDE
    # --------------------------------------------------------

    side = get_value(
        "side",
    )

    side_text = str(
        side or ""
    ).strip().lower()

    if side_text not in (
        "home",
        "away",
    ):

        side_text = ""

    # --------------------------------------------------------
    # ODDS
    # --------------------------------------------------------

    target = get_value(
        "target_odds",
        "targetOdds",
        "odds",
        "target",
        "combined_odds",
        "combinedOdds",
        "total_odds",
        "totalOdds",
    )

    if isinstance(
        target,
        dict,
    ):

        target = first_value(
            target,
            (
                "value",
                "target",
                "odds",
                "amount",
                "number",
            ),
        )

    target_text = ""

    if target is not None:

        target_text = str(
            target
        ).strip()

    # --------------------------------------------------------
    # NUMBER OF GAMES
    # --------------------------------------------------------

    games = get_value(
        "games",
        "picks",
        "count",
        "legs",
        "number_of_picks",
        "numberOfPicks",
    )

    games_text = ""

    if games is not None:

        try:

            games_number = int(
                float(games)
            )

            if games_number > 0:
                games_text = str(
                    games_number
                )

        except Exception:

            games_text = str(
                games
            ).strip()

    # --------------------------------------------------------
    # WINDOW
    # --------------------------------------------------------

    window = get_value(
        "window",
        "period",
        "range",
        "time",
    )

    window_text = str(
        window or "today"
    ).strip().lower()

    if window_text in (
        "tonight",
    ):

        final_window = "tonight"

    elif window_text in (
        "tomorrow",
    ):

        final_window = "tomorrow"

    elif window_text in (
        "long",
        "week",
        "weekend",
        "future",
    ):

        final_window = "long"

    else:

        final_window = "today"

    # --------------------------------------------------------
    # BUILD TEXT FROM THE CURRENT FRONTEND
    # --------------------------------------------------------

    if not text:

        parts = []

        # Ticket mode
        if mode_text in mode_map:

            parts.append(
                mode_map[mode_text]
            )

        # Side
        if side_text:

            parts.append(
                side_text
            )

        # Target odds
        if target_text:

            parts.append(
                target_text + " odds"
            )

        # Number of games
        elif games_text:

            parts.append(
                games_text + " games"
            )

        # Time window
        parts.append(
            final_window
        )

        text = " ".join(parts).strip()

    # --------------------------------------------------------
    # FALLBACK FOR STRAIGHT WIN
    # --------------------------------------------------------

    if not text:

        straight = get_value(
            "straight_win",
            "straightWin",
            "straight",
            "is_straight_win",
            "isStraightWin",
        )

        if (
            straight is True
            or str(straight).lower()
            in (
                "true",
                "yes",
                "1",
                "on",
            )
        ):

            text = "straight win"

            if target_text:

                text += (
                    " "
                    + target_text
                    + " odds"
                )

            text += (
                " "
                + final_window
            )

    # --------------------------------------------------------
    # FINAL CHECK
    # --------------------------------------------------------

    if not text:

        print(
            "❌ /api/build received:"
        )

        print(data)

        return jsonify(
            error="Empty build request."
        ), 400

    # --------------------------------------------------------
    # RATE LIMIT
    # --------------------------------------------------------

    if too_fast(
        client_ip()
    ):

        return jsonify(
            error=(
                "Slow down. "
                "Try again in a minute."
            )
        ), 429

    # --------------------------------------------------------
    # LOG
    # --------------------------------------------------------

    print(
        "🎯 /api/build request:",
        text,
    )

    # --------------------------------------------------------
    # SEND TO SMART TICKET ENGINE
    # --------------------------------------------------------

    q, busy = start_turn(
        session,
        text[:500],
    )

    if busy:

        return busy

    return stream_response(q)


