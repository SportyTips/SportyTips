@app.post("/api/chat")
def chat():

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    text = str(
        data.get(
            "message",
            "",
        )
    ).strip()

    session = str(
        data.get(
            "session",
            "",
        )
    ).strip()

    text = text[:500]

    session = session[:64]

    if not text:

        return jsonify(
            error="Empty message."
        ), 400

    if not session:

        return jsonify(
            error="Missing session."
        ), 400

    if too_fast(
        client_ip()
    ):

        return jsonify(
            error=(
                "Slow down. "
                "Try again in a minute."
            )
        ), 429

    q, busy = start_turn(
        session,
        text,
    )

    if busy:

        return busy

    return stream_response(
        q
    )


# ============================================================
# /api/build
#
# Supports different versions of the frontend.
#
# Examples accepted:
#
# {
#   "session": "123",
#   "message": "straight win 10 odds today"
# }
#
# OR:
#
# {
#   "session": "123",
#   "spec": {
#       "straight_win": true,
#       "target_odds": 10,
#       "window": "today"
#   }
# }
#
# OR:
#
# {
#   "session": "123",
#   "straight_win": true,
#   "odds": 10,
#   "window": "today"
# }
# ============================================================

@app.post("/api/build")
def api_build():

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    # --------------------------------------------------------
    # SESSION
    # --------------------------------------------------------

    session = str(
        data.get(
            "session",
            "",
        )
    ).strip()[:64]

    if not session:

        return jsonify(
            error="Missing session."
        ), 400

    # --------------------------------------------------------
    # DIRECT TEXT
    # --------------------------------------------------------

    text = ""

    direct_keys = (
        "message",
        "text",
        "prompt",
        "request",
        "query",
        "build",
    )

    for key in direct_keys:

        value = data.get(
            key
        )

        if value is None:
            continue

        if isinstance(
            value,
            str,
        ):

            value = value.strip()

            if value:

                text = value

                break

    # --------------------------------------------------------
    # HELPER
    # --------------------------------------------------------

    def first_value(
        obj,
        keys,
    ):

        if not isinstance(
            obj,
            dict,
        ):

            return None

        for key in keys:

            if key in obj:

                value = obj.get(
                    key
                )

                if value is not None:

                    return value

        return None

    # --------------------------------------------------------
    # SPEC
    # --------------------------------------------------------

    spec = data.get(
        "spec"
    )

    # Some frontend versions may send
    # spec as JSON text.
    if isinstance(
        spec,
        str,
    ):

        raw_spec = spec.strip()

        if raw_spec:

            try:

                parsed_spec = json.loads(
                    raw_spec
                )

                if isinstance(
                    parsed_spec,
                    dict,
                ):

                    spec = parsed_spec

            except Exception:

                if not text:

                    text = raw_spec

    # --------------------------------------------------------
    # BUILD TEXT FROM SPEC
    # --------------------------------------------------------

    if (
        not text
        and isinstance(
            spec,
            dict,
        )
    ):

        parts = []

        # ----------------------------------------------------
        # STRAIGHT WIN
        # ----------------------------------------------------

        straight = first_value(
            spec,
            (
                "straight_win",
                "straightWin",
                "straight",
                "is_straight_win",
                "isStraightWin",
            ),
        )

        if (
            straight is True
            or str(straight).lower()
            in (
                "true",
                "yes",
                "1",
                "on",
            )
        ):

            parts.append(
                "straight win"
            )

        # ----------------------------------------------------
        # TARGET ODDS
        # ----------------------------------------------------

        target = first_value(
            spec,
            (
                "target_odds",
                "targetOdds",
                "odds",
                "target",
                "combined_odds",
                "combinedOdds",
                "total_odds",
                "totalOdds",
            ),
        )

        # Nested odds object support.
        if isinstance(
            target,
            dict,
        ):

            target = first_value(
                target,
                (
                    "value",
                    "target",
                    "odds",
                    "amount",
                    "number",
                ),
            )

        if target is not None:

            target_text = str(
                target
            ).strip()

            if target_text:

                parts.append(
                    f"{target_text} odds"
                )

        # ----------------------------------------------------
        # NUMBER OF PICKS
        # ----------------------------------------------------

        picks = first_value(
            spec,
            (
                "picks",
                "count",
                "legs",
                "number_of_picks",
                "numberOfPicks",
            ),
        )

        if (
            target is None
            and picks is not None
        ):

            picks_text = str(
                picks
            ).strip()

            if picks_text:

                parts.append(
                    f"best {picks_text} picks"
                )

        # ----------------------------------------------------
        # WINDOW
        # ----------------------------------------------------

        window = first_value(
            spec,
            (
                "window",
                "period",
                "range",
                "time",
            ),
        )

        if window is None:

            window = "today"

        window_text = str(
            window
        ).strip().lower()

        if window_text in (
            "long",
            "week",
            "weekend",
            "future",
            "tomorrow",
        ):

            if window_text == "tomorrow":

                parts.append(
                    "tomorrow"
                )

            else:

                parts.append(
                    "long"
                )

        else:

            parts.append(
                "today"
            )

        # ----------------------------------------------------
        # RISK
        # ----------------------------------------------------

        risk = first_value(
            spec,
            (
                "risk",
                "risk_level",
                "riskLevel",
            ),
        )

        if risk:

            risk_text = str(
                risk
            ).strip()

            if risk_text:

                parts.append(
                    risk_text
                )

        # ----------------------------------------------------
        # DEFAULT
        # ----------------------------------------------------

        if not parts:

            parts.append(
                "best 5 picks today"
            )

        text = " ".join(
            parts
        )

    # --------------------------------------------------------
    # TOP-LEVEL FIELDS
    #
    # Handles frontend sending:
    #
    # {
    #   "straight_win": true,
    #   "odds": 10,
    #   "window": "today"
    # }
    # --------------------------------------------------------

    if not text:

        straight = data.get(
            "straight_win",
            data.get(
                "straightWin",
                data.get(
                    "straight",
                    False,
                ),
            ),
        )

        target = first_value(
            data,
            (
                "target_odds",
                "targetOdds",
                "odds",
                "target",
                "combined_odds",
                "combinedOdds",
                "total_odds",
                "totalOdds",
            ),
        )

        window = first_value(
            data,
            (
                "window",
                "period",
                "range",
            ),
        )

        if window is None:

            window = "today"

        parts = []

        if (
            straight is True
            or str(straight).lower()
            in (
                "true",
                "yes",
                "1",
                "on",
            )
        ):

            parts.append(
                "straight win"
            )

        if target is not None:

            target_text = str(
                target
            ).strip()

            if target_text:

                parts.append(
                    f"{target_text} odds"
                )

        window_text = str(
            window
        ).strip().lower()

        if window_text in (
            "long",
            "week",
            "weekend",
            "future",
        ):

            parts.append(
                "long"
            )

        elif window_text == "tomorrow":

            parts.append(
                "tomorrow"
            )

        else:

            parts.append(
                "today"
            )

        if parts:

            text = " ".join(
                parts
            )

    # --------------------------------------------------------
    # FINAL CHECK
    # --------------------------------------------------------

    if not text:

        print(
            "❌ /api/build received:"
        )

        print(
            data
        )

        return jsonify(
            error="Empty build request."
        ), 400

    # --------------------------------------------------------
    # RATE LIMIT
    # --------------------------------------------------------

    if too_fast(
        client_ip()
    ):

        return jsonify(
            error=(
                "Slow down. "
                "Try again in a minute."
            )
        ), 429

    # --------------------------------------------------------
    # LOG REQUEST
    # --------------------------------------------------------

    print(
        "🎯 /api/build request:",
        text,
    )

    # --------------------------------------------------------
    # SEND TO SMART TICKET ENGINE
    # --------------------------------------------------------

    q, busy = start_turn(
        session,
        text[:500],
    )

    if busy:

        return busy

    return stream_response(
        q
    )


