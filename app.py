CODE_OK = re.compile(
    r"^[A-Z0-9]{5,12}$"
)


# ============================================================
# GENERIC TICKET TOOL
# ============================================================

def _ticket_tool(
    work
):
    if too_fast(
        client_ip()
    ):
        return jsonify(
            error=(
                "Slow down. "
                "Try again in a minute."
            )
        ), 429

    try:
        result = work()

        if result is None:
            result = {}

        return jsonify(result)

    except Exception as exc:

        print(
            "Ticket tool error:",
            exc,
        )

        return jsonify(
            error=str(exc)[:300]
        ), 500


