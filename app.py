def api_safer():

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    session = str(
        data.get(
            "session",
            "",
        )
    ).strip()[:64]

    if not session:

        return jsonify(
            error="Missing session."
        ), 400

    message = (
        "Make this ticket safer. "
        "Use SportyBet selections only. "
        "Avoid DNB, negative handicaps "
        "and under selections."
    )

    if too_fast(
        client_ip()
    ):

        return jsonify(
            error="Slow down."
        ), 429

    q, busy = start_turn(
        session,
        message,
    )

    if busy:

        return busy

    return stream_response(
        q
    )


