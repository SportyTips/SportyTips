_hits = {}


def client_ip():

    forwarded = request.headers.get(
        "X-Forwarded-For",
        "",
    )

    if forwarded:

        return (
            forwarded
            .split(",")[0]
            .strip()
        )

    return (
        request.remote_addr
        or "?"
    )


def too_fast(
    key,
    limit=RATE_LIMIT,
):

    now = time.time()

    recent = [
        timestamp
        for timestamp in _hits.get(
            key,
            [],
        )
        if now - timestamp < RATE_WINDOW
    ]

    if len(recent) >= limit:

        _hits[key] = recent

        return True

    recent.append(
        now
    )

    _hits[key] = recent

    return False


# ============================================================
# ONLY ONE TICKET BUILD AT A TIME
# ============================================================

RUN_LOCK = threading.Lock()

_active_sessions = set()


# ============================================================
# RUN BOT TURN
# ============================================================

def run_turn(
    session,
    text,
    q,
):

    _ctx.q = q

    try:

        with RUN_LOCK:

            bot.handle_text(
                session,
                text,
            )

    except Exception as exc:

        print(
            "Ticket error:",
            exc,
        )

        q.put(
            {
                "type": "text",
                "html": (
                    "❌ "
                    + html.escape(
                        str(exc)
                    )
                ),
            }
        )

    finally:

        _active_sessions.discard(
            session
        )

        q.put(None)

        try:

            del _ctx.q

        except Exception:

            pass


# ============================================================
# START BOT TURN
# ============================================================

def start_turn(
    session,
    text,
):

    # Same session is already building.
    if session in _active_sessions:

        return (
            None,
            (
                jsonify(
                    error=(
                        "I'm still building "
                        "your ticket. "
                        "Wait for it to finish."
                    )
                ),
                429,
            ),
        )

    # Another ticket is being built.
    if RUN_LOCK.locked():

        return (
            None,
            (
                jsonify(
                    error=(
                        "SportyTips is still "
                        "building another ticket. "
                        "Please wait for it to finish."
                    )
                ),
                429,
            ),
        )

    _active_sessions.add(
        session
    )

    q = queue.Queue()

    thread = threading.Thread(
        target=run_turn,
        args=(
            session,
            text,
            q,
        ),
        daemon=True,
        name="sportytips-ticket",
    )

    thread.start()

    return (
        q,
        None,
    )


# ============================================================
# STREAM RESPONSE
# ============================================================

def stream_response(q):

    def stream():

        while True:

            try:

                item = q.get(
                    timeout=20
                )

            except queue.Empty:

                # Keep Render/browser connection alive.
                yield "\n"

                continue

            if item is None:

                break

            yield (
                json.dumps(
                    item,
                    ensure_ascii=False,
                )
                + "\n"
            )

    return Response(
        stream(),
        mimetype="application/x-ndjson",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
            "Connection": "keep-alive",
        },
    )


