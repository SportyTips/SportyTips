@app.post("/api/chat")
def chat():

    data = (
        request.get_json(
            silent=True
        )
        or {}
    )

    text = str(
        data.get(
            "message",
            "",
        )
    ).strip()

    session = str(
        data.get(
            "session",
            "",
        )
    ).strip()

    text = text[:500]
    session = session[:64]

    if not text:

        return jsonify(
            error="Empty message."
        ), 400

    if not session:

        return jsonify(
            error="Missing session."
        ), 400

    if too_fast(
        client_ip()
    ):

        return jsonify(
            error=(
                "Slow down. "
                "Try again in a minute."
            )
        ), 429

    q, busy = start_turn(
        session,
        text,
    )

    if busy:

        return busy

    return stream_response(q)


