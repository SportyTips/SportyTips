def web_send_message(
    chat_id,
    text,
):

    text = str(
        text or ""
    )

    kept = []

    for line in text.split("\n"):

        if not HIDE_LINES.search(line):
            kept.append(line)

    cleaned = "\n".join(
        kept
    ).strip()

    cleaned = re.sub(
        r"\n{3,}",
        "\n\n",
        cleaned,
    )

    if not cleaned:

        cleaned = (
            "I couldn't get that right now. "
            "Please try again in a minute."
        )

    cleaned = (
        cleaned
        .replace(
            "&#x27;",
            "'",
        )
        .replace(
            "&#39;",
            "'",
        )
        .replace(
            "&quot;",
            '"',
        )
    )

    _emit(
        {
            "type": "text",
            "html": _rebrand(cleaned),
        }
    )


